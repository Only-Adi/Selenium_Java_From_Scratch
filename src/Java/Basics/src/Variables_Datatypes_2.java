
public class Variables_Datatypes_2
{

	public static void main(String[] args) {
		
		
//		Data types in JAVA 
		
		int num1 = 1; // Integer
		String value1 = "Learning Java"; // Strings
		char Cval2 = 'a'; // character inside ''(single Quotation marks)
		float value2 = 2.67f; // float (decimal number)
		double Dvalue3 = 233.45454; //double (large decimal numbers)
        boolean Bvalue4 = true; // Boolean values (true)
        boolean Bvalue5 = false;// Boolean values (false)
        
        System.out.println(num1);
        System.out.println(value1);
        System.out.println(Cval2);
        System.out.println(value2);
        System.out.println(Dvalue3);
        System.out.println(Bvalue4);
        System.out.println(Bvalue5); 
        
        System.out.println("My integer value is "+ num1); // concatenation only happens with a "+" operator between String and Integer 
        

	}

}
